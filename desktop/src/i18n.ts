export type TranslationKey = keyof typeof ru;

export function t(key: TranslationKey, values: Record<string, string> = {}): string {
  const template: string = ru[key];
  return Object.entries(values).reduce<string>((text, [name, value]) => text.replaceAll(`{${name}}`, value), template);
}

export function presentValue(value: unknown): string {
  if (typeof value === "boolean") return t(value ? "value.true" : "value.false");
  if (typeof value === "string") {
    const key = `value.${value}` as TranslationKey;
    if (key in ru) return t(key);
  }
  return typeof value === "object" ? JSON.stringify(value) : String(value);
}

export function presentKey(key: string): string {
  const translationKey = `key.${key}` as TranslationKey;
  return translationKey in ru ? t(translationKey) : key.replaceAll("_", " ");
}
